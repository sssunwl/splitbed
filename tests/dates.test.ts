import { describe, expect, it } from 'vitest';

import { addDays, diffDays, eachNight, isWithin } from '../src/engine/dates';

describe('addDays', () => {
  it.each([
    ['2026-01-15', 0, '2026-01-15'],
    ['2026-01-15', 1, '2026-01-16'],
    ['2026-01-31', 1, '2026-02-01'],
    ['2027-12-31', 1, '2028-01-01'],
    ['2028-02-28', 1, '2028-02-29'],
    ['2028-02-29', 1, '2028-03-01'],
    ['2027-02-28', 1, '2027-03-01'],
    ['2026-03-01', -1, '2026-02-28'],
  ])('addDays(%s, %i) returns %s', (date, days, expected) => {
    expect(addDays(date, days)).toBe(expected);
  });
});

describe('diffDays', () => {
  it.each([
    ['2026-01-15', '2026-01-15', 0],
    ['2026-01-15', '2026-01-16', 1],
    ['2026-01-31', '2026-02-01', 1],
    ['2027-12-31', '2028-01-01', 1],
    ['2028-02-28', '2028-03-01', 2],
    ['2027-02-28', '2027-03-01', 1],
    ['2026-01-20', '2026-01-15', -5],
    ['2026-01-01', '2027-01-01', 365],
  ])('diffDays(%s, %s) returns %i', (from, to, expected) => {
    expect(diffDays(from, to)).toBe(expected);
  });
});

describe('eachNight', () => {
  it.each([
    ['2026-01-01', '2026-01-01', []],
    ['2026-01-01', '2026-01-02', ['2026-01-01']],
    ['2026-01-01', '2026-01-03', ['2026-01-01', '2026-01-02']],
    ['2026-01-31', '2026-02-02', ['2026-01-31', '2026-02-01']],
    ['2027-12-31', '2028-01-02', ['2027-12-31', '2028-01-01']],
    ['2028-02-28', '2028-03-01', ['2028-02-28', '2028-02-29']],
    ['2027-02-28', '2027-03-01', ['2027-02-28']],
    ['2026-01-03', '2026-01-01', []],
  ])('eachNight(%s, %s) returns the expected nights', (from, to, expected) => {
    expect(eachNight(from, to)).toEqual(expected);
  });
});

describe('isWithin', () => {
  it.each([
    ['2026-01-01', null, null, false],
    ['2030-12-31', null, null, false],
    ['2026-01-10', '2026-01-10', null, true],
    ['2026-01-09', '2026-01-10', null, false],
    ['2026-01-09', null, '2026-01-10', true],
    ['2026-01-10', null, '2026-01-10', false],
    ['2026-01-10', '2026-01-10', '2026-01-20', true],
    ['2026-01-20', '2026-01-10', '2026-01-20', false],
    ['2026-01-15', '2026-01-10', '2026-01-20', true],
    ['2026-01-09', '2026-01-10', '2026-01-20', false],
  ])(
    'isWithin(%s, %s, %s) returns %s',
    (date, from, to, expected) => {
      expect(isWithin(date, from, to)).toBe(expected);
    },
  );
});
